#!/bin/sh
set -eu

config_path=${NUVITAE_COMMUNITY_CONFIG_PATH:-.community.env}

if [ -e "$config_path" ]; then
  printf '%s\n' "Community installation is already initialized at $config_path; existing configuration was preserved."
  exit 0
fi

config_dir=$(dirname "$config_path")
if [ ! -d "$config_dir" ]; then
  printf '%s\n' "Community configuration directory does not exist: $config_dir" >&2
  exit 1
fi

generate_secret() {
  # 48 bytes from the operating-system CSPRNG, encoded as 96 hexadecimal characters.
  od -An -N48 -tx1 /dev/urandom | tr -d ' \n'
}

umask 077
temporary_path="${config_path}.tmp.$$"
if [ -e "$temporary_path" ]; then
  printf '%s\n' "Community bootstrap temporary path already exists: $temporary_path" >&2
  exit 1
fi
postgres_password=$(generate_secret)
queue_password=$(generate_secret)
community_access_secret=$(generate_secret)
private_storage_signing_secret=$(generate_secret)
provider_session_encryption_secret=$(generate_secret)

{
  printf '%s\n' '# Generated by scripts/community-bootstrap.sh. Keep this file private and do not commit it.'
  printf '%s\n' 'POSTGRES_USER=nuvitae'
  printf '%s\n' "POSTGRES_PASSWORD=$postgres_password"
  printf '%s\n' 'POSTGRES_DB=nuvitae'
  printf '%s\n' "QUEUE_PASSWORD=$queue_password"
  printf '%s\n' "NUVITAE_COMMUNITY_ACCESS_SECRET=$community_access_secret"
  printf '%s\n' 'NUVITAE_COMMUNITY_SESSION_TTL_SECONDS=86400'
  printf '%s\n' 'NUVITAE_COMMUNITY_COOKIE_SECURE=true'
  printf '%s\n' 'NUVITAE_COMMUNITY_FUNNEL_TELEMETRY_ENABLED=false'
  printf '%s\n' "NUVITAE_PRIVATE_STORAGE_SIGNING_SECRET=$private_storage_signing_secret"
  printf '%s\n' "NUVITAE_PROVIDER_SESSION_ENCRYPTION_SECRET=$provider_session_encryption_secret"
  printf '%s\n' 'NUVITAE_LOCAL_PLAY_MODE=false'
} >"$temporary_path"

chmod 600 "$temporary_path"
mv "$temporary_path" "$config_path"

printf '%s\n' "Community configuration created at $config_path with owner-only permissions."
printf '%s\n' 'No secrets were printed. Retrieve the owner access secret deliberately with:'
printf '%s\n' '  sh scripts/community-owner-secret.sh'
