#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd -- "${script_dir}/.." && pwd)"
config_dir="$(mktemp -d "${TMPDIR:-/tmp}/nuvitae-community-alpha.XXXXXX")"
config_path="${config_dir}/community.env"

export LOCAL_UID="${LOCAL_UID:-$(id -u)}"
export LOCAL_GID="${LOCAL_GID:-$(id -g)}"
export COMPOSE_PROJECT_NAME="${COMPOSE_PROJECT_NAME:-nuvitae-alpha-${GITHUB_RUN_ID:-$$}-${GITHUB_RUN_ATTEMPT:-1}}"
export NUVITAE_COMMUNITY_CONFIG_PATH="$config_path"

compose() {
  docker compose \
    --env-file "$config_path" \
    -f "$repo_root/compose.yml" \
    -f "$repo_root/.github/compose.community-alpha.yml" \
    "$@"
}

cleanup() {
  local status=$?
  compose --profile test down --remove-orphans >/dev/null 2>&1 || true
  rm -rf "$config_dir"
  exit "$status"
}
trap cleanup EXIT INT TERM

fail() {
  printf 'Community alpha install/session gate failed: %s\n' "$1" >&2
  exit 1
}

cd "$repo_root"

if ! docker compose version >/dev/null 2>&1; then
  fail "Docker Compose is required"
fi

if docker ps -aq \
  --filter "label=com.docker.compose.project=$COMPOSE_PROJECT_NAME" | grep -q .; then
  fail "Compose project already has containers"
fi
if docker volume ls -q \
  --filter "label=com.docker.compose.project=$COMPOSE_PROJECT_NAME" | grep -q .; then
  fail "Compose project already has volumes"
fi

sh scripts/community-bootstrap.sh
[ "$(stat -c '%a' "$config_path")" = "600" ] ||
  fail "generated Community configuration is not mode 600"

# Values are generated by the bootstrap helper (hex/fixed booleans only).
# Export them without printing so Compose and the browser fixture receive the
# normal Community configuration while secrets stay out of the release log.
set -a
# shellcheck disable=SC1090
. "$config_path"
set +a

compose config --quiet

compose build workspace web api worker
compose --profile test build community-alpha-playwright
compose run --rm --no-deps workspace pnpm install --frozen-lockfile

compose up -d --build postgres queue api worker web
compose up --wait postgres queue api worker web

mapfile -t running_services < <(compose ps --services --status running | sort)
expected_services=(api postgres queue web worker)
if [ "${running_services[*]}" != "${expected_services[*]}" ]; then
  printf 'Expected services: %s\n' "${expected_services[*]}" >&2
  printf 'Running services: %s\n' "${running_services[*]}" >&2
  fail "Community service inventory is not healthy"
fi

web_port="$(compose port web 3000)"
[ "$web_port" = "127.0.0.1:3000" ] ||
  fail "web is not published only on 127.0.0.1:3000"

for internal in "api:3001" "postgres:5432" "queue:6379"; do
  service="${internal%%:*}"
  port="${internal##*:}"
  if compose port "$service" "$port" 2>/dev/null | grep -q .; then
    fail "$service unexpectedly publishes port $port"
  fi
done

curl --fail --silent --show-error http://localhost:3000/health >/dev/null

before_status="$(curl --silent --output /dev/null --write-out '%{http_code}' \
  http://localhost:3000/api/resumes)"
[ "$before_status" = "401" ] ||
  fail "protected API did not fail closed before sign-in"

login_headers="$(
  curl --silent --show-error --dump-header - --output /dev/null \
    --request POST \
    --header 'Content-Type: application/json' \
    --data-binary @- \
    http://localhost:3000/api/community-auth/session <<EOF
{"accessSecret":"$NUVITAE_COMMUNITY_ACCESS_SECRET"}
EOF
)"
session_cookie="$(
  printf '%s' "$login_headers" |
    sed -n 's/^[Ss]et-[Cc]ookie: \(nuvitae_community_session=[^;]*\).*/\1/p' |
    tr -d '\r' |
    head -n 1
)"
unset login_headers
[ -n "$session_cookie" ] || fail "owner sign-in did not create a session cookie"

status_body="$(
  curl --fail --silent --show-error \
    --header "Cookie: $session_cookie" \
    http://localhost:3000/api/community-auth/session/status
)"
[ "$status_body" = '{"authenticated":true}' ] ||
  fail "owner session was not authenticated"

compose down --remove-orphans
compose up -d postgres queue api worker web
compose up --wait postgres queue api worker web

restart_status="$(
  curl --fail --silent --show-error \
    --header "Cookie: $session_cookie" \
    http://localhost:3000/api/community-auth/session/status
)"
[ "$restart_status" = '{"authenticated":true}' ] ||
  fail "owner session did not survive normal Compose restart"

logout_status="$(
  curl --silent --output /dev/null --write-out '%{http_code}' \
    --request DELETE \
    --header "Cookie: $session_cookie" \
    http://localhost:3000/api/community-auth/session
)"
[ "$logout_status" = "204" ] || fail "owner logout did not return 204"

revoked_status="$(
  curl --fail --silent --show-error \
    --header "Cookie: $session_cookie" \
    http://localhost:3000/api/community-auth/session/status
)"
unset session_cookie
[ "$revoked_status" = '{"authenticated":false}' ] ||
  fail "revoked session remained authenticated"

compose --profile test run --rm --no-deps community-alpha-playwright \
  pnpm exec playwright test \
    --config=playwright.community-alpha.config.ts \
    tests/e2e/community/community-owner-session.e2e.test.ts

printf '%s\n' \
  "Community alpha clean install/session gate: passed" \
  "Fresh Compose project: passed" \
  "Service health and loopback exposure: passed" \
  "Normal restart persistence: passed" \
  "Browser owner session and logout revocation: passed" \
  "No real provider was invoked."
